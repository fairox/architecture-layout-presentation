"""Generate the files the web configurator serves from the Python package.

    python tools/build_web.py          # write them
    python tools/build_web.py --check  # exit 1 if they are out of date (CI)

- web/archicad/BuildBoard.py: one standard-library file made from the package's
  client, board builder, board-package and runner modules, so it can be dropped
  into the Tapir palette's script folder. Edit the package, not this file.
- web/presets/<board>.json: every boards/<board>/board.json, plus index.json.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "src" / "archicad_toolkit"
WEB = ROOT / "web"
MODULES = [
    "client.py",
    "presentation/geometry.py",
    "presentation/picture_object.py",
    "presentation/board.py",
    "presentation/package.py",
    "presentation/runner.py",
]
INTERNAL_IMPORT = re.compile(r"^from archicad_toolkit[\w.]* import (\([^)]*\)|[^\n]*)\n", re.MULTILINE)
DOCSTRING = re.compile(r'^\s*"""(.*?)"""\n', re.DOTALL)


def bundle() -> str:
    parts = []
    for name in MODULES:
        src = (PKG / name).read_text(encoding="utf-8")
        src = src.replace("from __future__ import annotations\n", "")
        src = INTERNAL_IMPORT.sub("", src)
        if name.endswith("runner.py"):
            src = DOCSTRING.sub("", src, count=1)
        parts.append(f"# {'=' * 24} {name} {'=' * 24}\n{src.strip()}\n")
    code = "\n\n".join(parts)
    build = hashlib.sha256(code.encode("utf-8")).hexdigest()[:12]
    doc = DOCSTRING.match((PKG / "presentation" / "runner.py").read_text(encoding="utf-8")).group(1).strip()
    head = (
        "#!/usr/bin/env python3\n"
        f'"""{doc}\n\n'
        f"Single-file build {build}, generated by tools/build_web.py from src/archicad_toolkit.\n"
        "Edit the package, not this file. Talks only to Archicad on 127.0.0.1. Standard library only.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        f'BOARD_SCRIPT_BUILD = "{build}"\n\n'
    )
    return head + code


def presets() -> dict[str, str]:
    out: dict[str, str] = {}
    index = []
    for cfg_path in sorted((ROOT / "boards").glob("*/board.json")):
        cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
        name = cfg_path.parent.name
        out[f"presets/{name}.json"] = json.dumps(cfg, indent=2, ensure_ascii=False) + "\n"
        lay = cfg["layout"]
        index.append({"id": name, "file": f"{name}.json", "title": f"{lay['id']}  {lay['name']}",
                      "size": f"{lay['width_mm']:g} x {lay['height_mm']:g} mm"})
    out["presets/index.json"] = json.dumps(index, indent=2, ensure_ascii=False) + "\n"
    return out


def outputs() -> dict[str, str]:
    return {"archicad/BuildBoard.py": bundle(), **presets()}


def main(argv: list[str]) -> int:
    stale = []
    for rel, text in outputs().items():
        path = WEB / rel
        if "--check" in argv:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote web/" + rel)
    if stale:
        print("Out of date (run python tools/build_web.py): " + ", ".join("web/" + s for s in stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
